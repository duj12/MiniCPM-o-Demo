"""两阶段 OmniLLM 描述 —— **提示词与判据集中放这里**。

## 两阶段是什么

| 阶段 | 何时 | 指令 | 期望输出 |
|---|---|---|---|
| `full`  | IC 判 **GREET**（新用户/换人），或（IC 直判 ANSWER 时）**首个带文本的 ASR 结果** | `FULL_INSTRUCTION` | 全量结构化描述（九类） |
| `delta` | 对话开始后**滚动**刷新 | `DELTA_INSTRUCTION` | 只报**变化**，简短 |

两阶段**共用一条连接、一个 system prompt**，靠 ``trigger_reply(text=…)``
注入不同指令来区分 —— 不中途 re-init（那会把已累积的视听 KV 上下文丢掉，
首字要重新热起来），也不开第二条连接（106:8006 上白白多占一路）。

（`ORCH_OMNI_DELTA_PERSONA=1` 时这套共用关系会被**刻意打破一次**：全量
做完后关掉重连、换成 `DELTA_SYSTEM_PROMPT` 再跑增量。理由见下面
「为什么增量轮压不短」。）

## 提示词怎么分

用户定调：「全量的是这个（`streaming_chat_demo.py` 的 `--describe` prompt）；
后面每轮 ASR 对话中间的，用简略的、描述变化」。

* `DEMO_DESCRIBE_PROMPT` —— demo 那份**逐字**（八类 + "输出：按八类分条"）；
* `FULL_INSTRUCTION` —— 护栏句 + 上面那份整段 ⇒ **全量阶段**用它（含格式要求）；
* `DESCRIBE_SYSTEM_PROMPT` —— 上面那份**去掉最后那句格式要求**，
  再加一条反对话护栏 ⇒ **八类清单留着、输出格式不在这里定**；
* `DELTA_INSTRUCTION` —— 一两句、只报变化；
* `DELTA_SYSTEM_PROMPT` —— **只报变化**的短人设。只有开
  `ORCH_OMNI_DELTA_PERSONA` 时才用得上，且**必须换连接**才生效。

关键约束：`system_prompt` 只在 `session.init` 时定一次（`input.append` 没有
逐轮 prompt 字段）。所以"这一轮要什么、什么格式"只能靠注入指令区分 ——
但也**只能到这一步**：注入指令带不动"描述哪些类别"，所以类别得留在
system prompt 里。

三次实测的过程记在 `DESCRIBE_SYSTEM_PROMPT` 上面那段注释里（抽象人设 ⇒
模型回"好的，现在开始录音"；整份进 system prompt ⇒ 增量轮压不下来；
摘掉类别 ⇒ 全量轮也不分条了）。

## 为什么增量轮压不短 —— 以及为什么只能靠换人设

用户问过：「必须 system 才可以吗，不能是每一轮的 prompt 限定输出吗？」
**每轮 prompt 这条路已经走了，就是 ``trigger_reply(text=…)``** —— 它确实
能驱动这一轮生成，但**在"输出哪些内容"上被 system prompt 盖住**。
2026-10-08 在 105 上试了三版，全都指向同一个结论：

1. system = 整份 demo（含八类），每轮注入"只描述变化、简短"
   ⇒ 增量仍 429~666 字；
2. system 同上，每轮注入"本轮**不要**按分类格式输出，只一两句"
   ⇒ 仍 311~679 字（跟格式对抗是白费力气）；
3. system **摘掉**八类清单，八类只放在每轮注入里
   ⇒ 增量短了，但**全量也塌了**（151 字普通段落，注入的八类清单
   根本没被采纳）。

第 3 条是关键证据：**每轮注入带不动"输出哪些类别"，system prompt 带得动。**
原因大概率是服务端把 system prompt 当**每轮 prompt 的前缀**重发
（cumulative_prompt），两段在同一轮 prompt 里，system 那份把注入的那份
盖住了 —— 属于观察后的推断，不是文档承诺。

每轮剩下的唯一硬旋钮是 ``max_new_tokens``（生成上限），那会把句子**截在
半句**上。这条链路的 VLM 是**原样**发给 Agent 的（见下「与 Agent 载荷的
关系」），半句话比"长但完整"更糟 ⇒ 不用。

⇒ 要「全量分条」与「增量简短」两副面孔，就得有**两份 system prompt**，
也就只能**关掉重连一次**（服务端不支持一条连接上第二次 `session.init`，
实测 ``ConnectionClosedOK: received 1000``）。同一时刻仍只有**一条**连接。


## system prompt 与指令的分工

* system prompt 决定**口吻**（描述而非对话）与**描述哪些类别**
  ——它每轮都作为 prompt 前缀，所以它比同一轮的注入指令权重更高；
* 注入指令决定**这一轮要什么、什么格式**（全量分条 / 只报变化）。

## 与 Agent 载荷的关系

描述文本经 `OmniDescription` 事件落进
`orchestrator/interaction/downstream.py` 的缓存，再由
`orchestrator/interaction/agent_sink.py` 的包装塞进 `on_answer` 的
``content.VLM``。**只在 `response.done`（生成完的整段）取值**，绝不用
`response.output.delta` 的 token 流 —— 那是半句话（见 `omni/client.py:_emit`）。
"""
from __future__ import annotations

#: `streaming_chat_demo.py:110-142` 的 `DESCRIBE_SYSTEM_PROMPT` —— **逐字复制**。
#:
#: 它是 demo `--describe` 模式用的那份（实测可用）。在这里的角色是
#: **全量阶段的指令**（拼进 `FULL_INSTRUCTION`），而**不是 system prompt** ——
#: 因为它自带"输出：按上述八类分条"这种**格式要求**，而 system prompt
#: 每轮都作为前缀重发，放进去就会一直压住增量轮的"只报变化、一两句"。
#: 2026-10-08 实测过这条：把整份放进 system prompt 后，增量轮照样吐
#: 一整份八类清单（311~679 字、每次 3.5~4s），仅靠注入指令里的
#: "本轮不要按分类格式输出"**压不回来**。
#:
#: ⚠️ 改它要跟 demo **两处一起改**；`tests/test_omni_describe_stage.py`
#: 有一条一致性断言盯着（两处漂移测试就红）。
DEMO_DESCRIBE_PROMPT = """你是一个视频监控/行为分析助手。请综合画面与语音，输出视频的结构化描述。
要求：只描述画面中实际可见、语音中实际可闻的信息；不确定的写"不可见/不确定"，绝不编造。
优先级：P0 为必答核心，P1 尽量回答，P2 在信息可见时回答。

【P0 人物信息】
- 性别、年龄段（如：青年男性、中年女性）
- 穿着（上衣/下装颜色、款式、有无配饰如眼镜帽子）

【P0 行为/运动状态】
- 人物行为和状态（站/坐/行走/挥手/操作某物等）
- 关键动作（如拿取、指向、蹲下、靠近某物）
- 相对距离变化：靠近/远离/保持不动（相对摄像头或相对他人）
- 运动方向与速度

【P1 环境描述】
- 场景类型（室内/室外、房间/街道等）
- 其他人（人数、在做什么）
- 环境要素（物品、光线、背景特征）

【P1 情绪状态】
- 根据人物表情、姿态、肢体语言判断
- 结合人物语音内容和语气判断

【P2 视线方向】
- 人物视线朝向（看向镜头/看向某物/看向某人），不可判断写"不可见"

【P2 人物与物体相对位置】
- 人物与画面中主要物体的相对位置（如：站在桌子右侧、靠近门口）

【P2 指向物体描述】
- 人物明确指向/拿起的物体（描述其外观），无则写"无"

输出：按上述八类分条，每条先写类别名再写内容。"""

#: demo prompt 最后那句**输出格式**要求 —— 它是 system prompt 里唯一
#: **被故意摘掉**的一句，见 `DESCRIBE_SYSTEM_PROMPT` 的注释。
FULL_FORMAT_LINE = "输出：按上述八类分条，每条先写类别名再写内容。"

#: 会话初始化时的 system prompt —— **只定口吻 + 描述哪些类别，不定输出格式**。
#:
#: = demo 那份**去掉最后一句"输出：按上述八类分条"**，再加一条反对话护栏。
#:
#: 三段实测（2026-10-08，105）换来的这一版：
#:
#: 1. system prompt 写成一句抽象的"你是描述助手" ⇒ 会话刚起 2.5s、
#:    视频帧才 ~4 帧时点火全量描述，模型回了 `'好的，现在开始录音。'`。
#:    **抽象人设定不住口吻** —— 得有"视频监控/行为分析助手"这个身份。
#: 2. system prompt = **整份** demo prompt（含最后一句） ⇒ 首轮正常，
#:    但**增量轮也照八类清单输出**（311~679 字、每次 3.5~4s），
#:    连"本轮不要按分类格式输出"都压不回来 —— system prompt 每轮都作为
#:    前缀重发，它的格式要求**权重高于同一轮的注入指令**。
#: 3. system prompt **不带**八类清单 ⇒ 换过来了：增量轮短了，可**全量轮
#:    也没了**（151 字普通段落，注入的八类清单根本没被采纳）——
#:    说明"描述哪些类别"也得待在 system prompt 里，注入指令带不动。
#:
#: ⇒ 结论：**类别留在 system prompt，只把"输出格式"挪到注入指令**。
#:   全量由 `FULL_INSTRUCTION`（= demo 原文，自带那句格式要求）驱动，
#:   增量由 `DELTA_INSTRUCTION` 要求"一两句、只报变化"。
#:
#: ⚠️ `system_prompt` 只能在 `session.init` 时定一次（`input.append` 没有
#: 逐轮 prompt），所以两个阶段**必须共用**它 —— 格式要求就只能在注入指令里，
#: 由"哪一轮"来决定。
DESCRIBE_SYSTEM_PROMPT = DEMO_DESCRIBE_PROMPT.replace(FULL_FORMAT_LINE, "").rstrip() + (
    "\n不要与用户对话，不要寒暄、提问、回应或反问，只输出描述文本。"
)

#: 全量描述指令（以 ``trigger_reply(text=…)`` 注入）—— **就是 demo 那份原文**。
#:
#: 用户定调：「全量的是这个（demo 的 prompt）；后面每轮 ASR 对话中间的，
#: 用简略的、描述变化」。所以这里整份拼进来 —— 直接引用常量、不再抄一遍，
#: 免得两处又漂移。前面只加一句针对 2026-10-08 那次走样
#: （模型回 `'好的，现在开始录音。'`）的护栏。
FULL_INSTRUCTION = (
    "直接输出对当前画面与语音的结构化描述。"
    "不要确认、不要回应、不要以“好的/收到/现在开始”之类的话开头，从第一个类别名直接开始。\n\n"
    + DEMO_DESCRIBE_PROMPT
)

#: 增量描述指令（对话开始后**滚动**注入）。
#:
#: ⚠️ 这里要求"简短"不是为了好看，而是**为了快**：描述要在 `AsrFinal`
#: 到达之前就生成完（见 plan 的主指标"发送的那一刻不生成"），而生成耗时
#: 与输出长度几乎线性。**但刻意不给字数硬指标** —— 硬指标会诱导模型
#: 在字数上做取舍（写一半、或为凑数复述上一轮），而"只报变化"这条约束
#: 本身就已经把它压得很短了。
#:
#: ## 为什么不叫它"别分条"，而是**顺着它的分条**来
#:
#: system prompt 里有八类清单（那是"全量分条"必需的，见
#: `DESCRIBE_SYSTEM_PROMPT` 的注释），而 system prompt 每轮都作为前缀重发，
#: **权重高于同一轮的注入指令**。2026-10-08 实测了两版对抗写法：
#:
#: * "只描述变化、简短" ⇒ 增量轮照旧吐整份八类清单（429~666 字）；
#: * "本轮**不要**按分类格式输出，只一两句" ⇒ 仍然 311~679 字，压不回来。
#:
#: ⇒ 结论：跟格式对抗是白费力气。改成**顺着它** —— 仍然按类别分条，
#: 但**只列这一轮真有变化的类别，每类一行**。模型乐意守格式，
#: 而"没变化的类别一个字都不要出现"这条把长度压下来了。
#:
#: ⚠️ 这里要求"简短"不是为了好看，而是**为了快**：描述要在 `AsrFinal`
#: 到达之前就生成完（见 plan 的主指标"发送的那一刻不生成"），而生成耗时
#: 与输出长度几乎线性。**但刻意不给字数硬指标** —— 硬指标会诱导模型
#: 在字数上做取舍（写一半、或为凑数复述上一轮）。
DELTA_INSTRUCTION = (
    "本轮只输出**发生变化**的内容，仍然按系统提示里的类别分条：\n"
    "- 只列**相对上一轮确实有变化**的类别，每类一行，尽量一句话说完；\n"
    "- 没有变化的类别**一个字都不要出现**（不要复述人物穿着、场景这类没变的东西）；\n"
    "- 完全没有变化就只回复“无变化”。\n"
    "不要与用户对话，不要确认，不要以“好的/收到”开头。"
)

#: **增量专用**的 system prompt —— 换人设重连后新连接的会话人设。
#:
#: ⚠️ 与 `DESCRIBE_SYSTEM_PROMPT` **不能共存于一条连接**（那正是本常量
#: 存在的原因，见模块文档「为什么增量轮压不短」）。只有开
#: `ORCH_OMNI_DELTA_PERSONA` 时才用：全量在 `DESCRIBE_SYSTEM_PROMPT` 的
#: 连接上做完 ⇒ 关掉 ⇒ 用这条重开 ⇒ 之后所有增量都在这条上滚。
#:
#: 三个刻意的取舍：
#:
#: * **八类清单一个字都没有** —— 它就是上面第 2/3 条实测里压不下来的那个
#:   源头。没有它，增量就只会是"一两句"。
#: * **"视频监控/行为分析助手"这个身份留着** —— 换成抽象的"你是描述助手"
#:   会让模型回 `'好的，现在开始录音。'`（见 `DESCRIBE_SYSTEM_PROMPT` 的
#:   注释第 1 条）。身份句是"口吻"的锚，不是格式的锚，留下它不吃亏。
#: * **"不对对话"护栏留着** —— 同理，是口吻不是格式。
#:
#: 代价：新连接的 KV 是空的，第一条增量要重新热（比同一条连接上的后续
#: 增量慢）。所以 `session._do_describe` 会给**换连接后的第一条**增量带上
#: 「上一轮描述」当参照物 —— 否则模型不知道"相对什么"在变。
DELTA_SYSTEM_PROMPT = (
    "你是一个视频监控/行为分析助手。请综合画面与语音，简短播报**相对上一轮的变化**。\n"
    "要求：只描述画面中实际可见、语音中实际可闻的信息；不确定的写“不可见/不确定”，绝不编造。\n"
    "只输出一两句话（最多三句）；没有变化就只回复“无变化”。\n"
    "不要与用户对话，不要寒暄、提问、回应或反问，只输出描述文本。"
)

#: 「无变化」的判据 —— 命中的**不下发**（保住上一份有效描述，见
#: `interaction/downstream.py` 的 `OmniDescription` 分支）。
_NO_CHANGE = (
    "无变化", "没有变化", "无明显变化", "暂无变化", "无显著变化",
    "画面无变化", "没有明显变化", "无",
)


def is_no_change(text: str) -> bool:
    """这句描述是不是"什么都没变"。

    只在**整句就是那句话**时算命中（去掉标点与空白后精确匹配）——
    不能写成 `"无变化" in text`：那样"人物无变化，但桌上多了一个杯子"
    这种**真有信息**的描述会被误丢。
    """
    s = (text or "").strip().strip("。.！!，,、；;：:~～ \t\n")
    return s in _NO_CHANGE


#: 对话式回复的开头（system prompt 没生效时的启发式告警）。
_CONVERSATIONAL_PREFIXES = (
    "您好", "你好", "您好，", "我可以", "请问", "很高兴", "有什么可以帮",
    "需要我", "我是", "当然", "好的，", "嗯，您", "抱歉",
)


def looks_conversational(text: str) -> bool:
    """这句描述**像不像在跟人对话**（而不是在描述画面）。

    ⚠️ 这是个**启发式告警**，不用来丢数据 —— 只用来在日志里提醒
    "prompt 没镇住，模型又开始聊天了"。判错了的代价只是一条日志。
    """
    s = (text or "").lstrip()
    return s.startswith(_CONVERSATIONAL_PREFIXES)
